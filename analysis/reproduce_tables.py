RNG = np.random.default_rng(42)


def arr(g, m):
    v = S[g][m].astype(float).values
    return v[~np.isnan(v)]


def ci(a):
    bs = np.array([RNG.choice(a, len(a), replace=True).mean() for _ in range(NB)])
    return a.mean(), np.percentile(bs, 2.5), np.percentile(bs, 97.5), len(a)


def diffci_unpaired(va, pi):
    bs = np.array([RNG.choice(pi, len(pi), True).mean() - RNG.choice(va, len(va), True).mean() for _ in range(NB)])
    return pi.mean() - va.mean(), np.percentile(bs, 2.5), np.percentile(bs, 97.5)


