def chk(val, printed, nd):
    """Format val with nd decimals and compare to the printed value."""
    if printed is None:
        return f"{val:.{nd}f}"
    same = abs(float(val) - float(printed)) <= 0.5 * 10 ** (-nd) + 1e-9  # equal after rounding (ties either way)
    tally["ok" if same else "DIFF"] += 1
    return f"{val:.{nd}f}" + ("" if same else f" **DIFF** [{printed:.{nd}f}]")


def chk_b(val, printed, nd, halfwidth):
    """Bootstrap bound: exact match, or within Monte-Carlo error of a 10,000-draw percentile
    (tolerance 0.05 x interval half-width + half a unit in the last printed digit)."""
    if round(float(val), nd) == round(float(printed), nd):
        tally["ok"] += 1
        return f"{val:.{nd}f}"
    if abs(val - printed) <= 0.05 * abs(halfwidth) + 0.5 * 10 ** (-nd):
        tally["ok (MC)"] += 1
        return f"{val:.{nd}f}~"
    tally["DIFF"] += 1
    return f"{val:.{nd}f} **DIFF** [{printed:.{nd}f}]"


def table(title, header, rows, note=None):
    md.extend([f"## {title}", ""])
    if note:
        md.extend([note, ""])
    md.append("| " + " | ".join(header) + " |")
    md.append("|" + "---|" * len(header))
    for r in rows:
        md.append("| " + " | ".join(str(c) for c in r) + " |")
    md.append("")


