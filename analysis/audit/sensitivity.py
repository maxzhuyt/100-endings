#!/usr/bin/env python3
"""Sensitivity of the paper's model-condition results to two measured problems (ERRATA A1, A2).

1. Truncated pipeline stories (A1): Table 2 contrasts recomputed on prompts whose pipeline story is
   complete (ends_mid_sentence False), and, more strictly, also not at the model's length ceiling.
2. Hidden endings (A2): the judge sees only the first 2,000 words of the continuation
   (metric/compute_*judge.py, truncate_words). At early positions of long stories the true ending is
   therefore not shown. We count those positions and recompute no-rate on positions where every story's
   ending is visible.

Reads results/scores, results/curves, data/stories. Writes analysis/audit/sensitivity.md and .csv files.
Paired statistics: mean of pipeline - vanilla over shared prompts; 95% CI = 2.5/97.5 percentiles of
10,000 bootstrap resamples of prompts (numpy default_rng(0)); p = two-sided paired t-test."""
import gzip, json, os, re
import numpy as np
import pandas as pd
from scipy import stats

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
OUT = os.path.join(R, "analysis", "audit")
CAP = 2000
SPLIT = re.compile(r'[.!?]["”’)]*\s+(?=[A-Z“"(\[])')


def split_sentences(text):  # identical to metric/run_cwb_endings.py
    b = [0] + [m.end() for m in SPLIT.finditer(text)]
    parts = []
    for i in range(len(b)):
        chunk = text[b[i]:(b[i + 1] if i + 1 < len(b) else len(text))].strip()
        if chunk:
            parts.append(chunk)
    return parts


def load(g):
    s = pd.read_csv(f"{R}/results/scores/{g}.csv", dtype={"story_id": str})
    s["model_slug"] = s.model_slug.fillna("")
    curves = {}
    for line in gzip.open(f"{R}/results/curves/{g}.jsonl.gz", "rt"):
        r = json.loads(line)
        curves[(r.get("model_slug") or "", r["story_id"])] = r["positions"]
    return s, curves


# Texts that are not redistributed: used when present (authors' cluster), else the approximation.
NP = os.environ.get("ENDINGS_PRIVATE_ROOT", "/project/jevans/maxzhuyt/narrative_project")
PRIVATE = {"new_yorker": [f"{NP}/NYER_83", f"{NP}/NYER_EXPANDED"],
           "storystar": [f"{NP}/BASELINE_CORPUS/storystar/sampled"]}
NSENT_CHECK = []


def hidden_flags(g, s, curves):
    """Per position: does the judged continuation exceed CAP words (true ending hidden)?
    Exact (from the text) where the text is in data/stories, else words*(1-pct/100)."""
    rows = []
    for _, st in s.iterrows():
        pos = curves[(st.model_slug, st.story_id)]
        cands = [f"{R}/data/stories/{g}/{st.story_id}.txt"] + [f"{d}/{st.story_id}.txt" for d in PRIVATE.get(g, [])]
        p = next((c for c in cands if os.path.exists(c)), None)
        sents = split_sentences(open(p, encoding="utf-8").read().strip()) if p else None
        if sents:
            NSENT_CHECK.append(len(sents) == st.n_sentences)
        for q in pos:
            if q["pct"] < 10:
                continue
            if sents:
                n = len(sents)
                i = min(range(1, n + 1), key=lambda k: abs(k / n * 100 - q["pct"]))
                cont = len(" ".join(sents[i:]).split())
                exact = True
            else:
                cont = st.words * (1 - q["pct"] / 100)
                exact = False
            rows.append(dict(group=g, model_slug=st.model_slug, story_id=st.story_id, pct=q["pct"],
                             no_rate=q["no_rate"], cont_words=cont, hidden=cont > CAP, exact=exact))
    return pd.DataFrame(rows)


def paired(a, b, rng):
    d = np.asarray(a) - np.asarray(b)
    bs = rng.choice(d, size=(10000, len(d)), replace=True).mean(1)
    return d.mean(), np.percentile(bs, 2.5), np.percentile(bs, 97.5), stats.ttest_1samp(d, 0).pvalue, len(d)


GROUPS = ["new_yorker", "tell_me_a_story", "storystar", "top10_zeroshot",
          "sonnet46_vanilla", "sonnet46_pipeline", "sonnet46_pipeline_nostep0",
          "opus46_vanilla", "opus46_pipeline", "gpt52_vanilla", "gpt52_pipeline"]
S, P = {}, []
for g in GROUPS:
    s, c = load(g)
    S[g] = s
    P.append(hidden_flags(g, s, c))
P = pd.concat(P)
print(f"sentence count of text == scores n_sentences: {sum(NSENT_CHECK)}/{len(NSENT_CHECK)} stories")
P.to_csv(f"{OUT}/positions_hidden_ending.csv.gz", index=False)

md = ["# Sensitivity of the model-condition results (generated by sensitivity.py)\n"]

# ---- 1. hidden endings
md += ["## Positions judged without the true ending (continuation > 2,000 words)\n",
       "Positions with pct ≥ 10. `exact` = computed from the story text with the metric's sentence splitter; "
       "`approx.` = words × (1 − pct/100) (Top-10 texts are not in this repository).\n",
       "| Group | median words | max words | positions | hidden-ending positions | share | NR on hidden | NR on visible | largest pct of a hidden-ending position |",
       "|---|---|---|---|---|---|---|---|---|"]
thr = {}
for g in GROUPS:
    q = P[P.group == g]
    hid = q[q.hidden]
    t = hid.pct.max() if len(hid) else 0
    thr[g] = t
    md.append(f"| {g} | {S[g].words.median():.0f} | {S[g].words.max():.0f} | {len(q)} | {len(hid)} | {len(hid)/len(q):.3f} | "
              f"{hid.no_rate.mean() if len(hid) else float('nan'):.3f} | {q[~q.hidden].no_rate.mean():.3f} | "
              f"{'exact' if q.exact.all() else 'approx.'}: {t:.1f} |")
def cut_for(groups):  # smallest multiple of 5 above every hidden-ending position in these groups
    return 5 * (int(max(thr[g] for g in groups) // 5) + 1)
CUT_C = cut_for(GROUPS[:4])
CUT_T = cut_for(GROUPS[4:])
md += ["", f"Corpora: every position at pct ≥ {CUT_C} shows the judge the true ending (Top-10 by approximation). "
       f"Model conditions of Table 2: every position at pct ≥ {CUT_T} does (exact). "
       f"NR(≥{CUT_C}) and NR(≥{CUT_T}) below average no-rate over those positions only. "
       "Late NR (pct ≥ 80) is unaffected in every group.\n"]

# ---- corpora on NR >= CUT
def nr_from(g, lo):
    q = P[(P.group == g) & (P.pct >= lo)]
    return q.groupby(["model_slug", "story_id"]).no_rate.mean()

md += [f"## Corpora (Table 1) on positions ≥ {CUT_C}%\n", f"| Group | n | Mean NR (printed definition) | NR(≥{CUT_C}) | Late NR |", "|---|---|---|---|---|"]
for g in GROUPS[:4]:
    s = S[g]
    md.append(f"| {g} | {len(s)} | {s.mean_nr.mean():.3f} | {nr_from(g, CUT_C).mean():.3f} | {s.late_nr.mean():.3f} |")

# ---- 2. Table 2 paired contrasts under subsets
rng = np.random.default_rng(0)
rows = []
pairs = [("sonnet46", "sonnet46_pipeline", "sonnet46_vanilla"), ("opus46", "opus46_pipeline", "opus46_vanilla"),
         ("gpt52", "gpt52_pipeline", "gpt52_vanilla"), ("sonnet46_nostep0", "sonnet46_pipeline_nostep0", "sonnet46_vanilla")]
for name, gp, gv in pairs:
    p_, v_ = S[gp].copy(), S[gv].copy()
    p_["nr60"] = p_.story_id.map(nr_from(gp, CUT_T).droplevel(0))
    v_["nr60"] = v_.story_id.map(nr_from(gv, CUT_T).droplevel(0))
    m = p_.merge(v_, on="story_id", suffixes=("_p", "_v"))
    subsets = {"all 32 prompts": m,
               "pipeline story complete": m[~m.ends_mid_sentence_p.astype(bool)],
               "complete and below length ceiling": m[~m.ends_mid_sentence_p.astype(bool) & ~m.at_length_ceiling_p.astype(bool)]}
    for sub, d in subsets.items():
        for met in ("mean_nr", "nr60", "late_nr", "retain_pct", "ir60", "eqbench"):
            dd = d[[f"{met}_p", f"{met}_v"]].dropna()
            mu, lo, hi, p, n = paired(dd[f"{met}_p"], dd[f"{met}_v"], rng)
            rows.append(dict(model=name, subset=sub, metric=met, n_pairs=n, diff=mu, ci_lo=lo, ci_hi=hi, paired_t_p=p,
                             words_pipeline_median=d.words_p.median(), words_vanilla_median=d.words_v.median()))
T = pd.DataFrame(rows)
T.to_csv(f"{OUT}/table2_sensitivity.csv", index=False)
md += ["", "## Table 2 contrasts (pipeline − vanilla), paired over prompts\n",
       f"| Model | Subset | n | words (pipe / van, median) | Δ Mean NR | Δ NR(≥{CUT_T}) | Δ Late NR | Δ Retain (pp) | Δ EQ-Bench |", "|---|---|---|---|---|---|---|---|---|"]
for (mo, sub), d in T.groupby(["model", "subset"], sort=False):
    c = {r.metric: f"{r.diff:+.3f} [{r.ci_lo:+.3f}, {r.ci_hi:+.3f}]" for r in d.itertuples()}
    rt = d[d.metric == "retain_pct"].iloc[0]
    c["retain_pct"] = f"{rt['diff']:+.1f} [{rt.ci_lo:+.1f}, {rt.ci_hi:+.1f}]"
    e = d[d.metric == "eqbench"].iloc[0]
    c["eqbench"] = f"{e['diff']:+.2f} [{e.ci_lo:+.2f}, {e.ci_hi:+.2f}]"
    r0 = d.iloc[0]
    md.append(f"| {mo} | {sub} | {int(d[d.metric=='mean_nr'].n_pairs.iloc[0])} | {r0.words_pipeline_median:.0f} / {r0.words_vanilla_median:.0f} | "
              f"{c['mean_nr']} | {c['nr60']} | {c['late_nr']} | {c['retain_pct']} | {c['eqbench']} |")
open(f"{OUT}/sensitivity.md", "w").write("\n".join(md) + "\n")
print("\n".join(md))
